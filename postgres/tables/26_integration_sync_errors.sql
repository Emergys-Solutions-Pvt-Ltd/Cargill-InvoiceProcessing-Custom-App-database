-- =====================================================================
-- app.integration_sync_errors - record-level and job-level problems of a sync job
-- stage: fetch | mapping | validation | persistence | review
--   review = the record was synced but needs a person (e.g. reversed in the source after
--            processing had started, so its status was not changed automatically)
-- details holds field names and sanitized values only - never credentials or tokens.
-- Purged together with its job (retention policy, usp_integration_purge_history).
-- Depends on: app.integration_sync_jobs, app.integration_profiles
-- Idempotent: creates the table when missing; the UPGRADES section brings
-- existing databases up to date. Run through deploy_schema.sql.
-- =====================================================================
CREATE TABLE IF NOT EXISTS app.integration_sync_errors (
    id              bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_integration_sync_errors PRIMARY KEY,
    job_id          integer         NOT NULL CONSTRAINT fk_sync_errors_job REFERENCES app.integration_sync_jobs (id) ON DELETE CASCADE,
    profile_id      integer         NULL CONSTRAINT fk_sync_errors_profile REFERENCES app.integration_profiles (id) ON DELETE SET NULL,
    stage           varchar(20)     NOT NULL,
    external_key    varchar(200)    NULL,
    message         varchar(2000)   NOT NULL,
    details         jsonb           NULL,
    created_at      timestamptz(3)  NOT NULL DEFAULT now(),
    CONSTRAINT ck_sync_errors_stage CHECK (stage IN ('fetch', 'mapping', 'validation', 'persistence', 'review'))
);

CREATE INDEX IF NOT EXISTS ix_sync_errors_job ON app.integration_sync_errors (job_id, id);

