-- =====================================================================
-- app.integration_sync_jobs - synchronization queue AND execution history
-- Workers claim 'queued' rows whose run_after has passed (FOR UPDATE SKIP LOCKED).
-- At most one queued/running job per integration (partial unique index), so scheduled and
-- manual runs can never overlap. Counters are updated in the same transaction as each
-- processed page, so they always match what was committed.
-- Status: queued -> running -> succeeded | partially_succeeded | failed | cancelled
-- Depends on: app.integrations, app_auth.users
-- Idempotent: creates the table when missing; the UPGRADES section brings
-- existing databases up to date. Run through deploy_schema.sql.
-- =====================================================================
CREATE TABLE IF NOT EXISTS app.integration_sync_jobs (
    id                  integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_integration_sync_jobs PRIMARY KEY,
    integration_id      integer         NOT NULL CONSTRAINT fk_sync_jobs_integration
                                        REFERENCES app.integrations (id) ON DELETE CASCADE,
    trigger_type        varchar(20)     NOT NULL,                   -- scheduled | manual | retry
    requested_by        integer         NULL CONSTRAINT fk_sync_jobs_requested_by REFERENCES app_auth.users (id) ON DELETE SET NULL,
    status              varchar(30)     NOT NULL DEFAULT 'queued',
    attempt             integer         NOT NULL DEFAULT 1,
    max_attempts        integer         NOT NULL DEFAULT 3,
    retry_of_job_id     integer         NULL CONSTRAINT fk_sync_jobs_retry_of REFERENCES app.integration_sync_jobs (id) ON DELETE SET NULL,
    run_after           timestamptz(3)  NOT NULL DEFAULT now(),
    started_at          timestamptz(3)  NULL,
    finished_at         timestamptz(3)  NULL,
    heartbeat_at        timestamptz(3)  NULL,
    worker_id           varchar(100)    NULL,
    cancel_requested    boolean         NOT NULL DEFAULT false,
    records_fetched     integer         NOT NULL DEFAULT 0,
    records_created     integer         NOT NULL DEFAULT 0,
    records_updated     integer         NOT NULL DEFAULT 0,
    records_unchanged   integer         NOT NULL DEFAULT 0,         -- skipped: no change since last sync
    records_rejected    integer         NOT NULL DEFAULT 0,         -- failed mapping / validation
    records_failed      integer         NOT NULL DEFAULT 0,         -- failed to persist
    pages_processed     integer         NOT NULL DEFAULT 0,
    profile_stats       jsonb           NOT NULL DEFAULT '{}'::jsonb, -- per profile id: counters + watermark
    error_summary       varchar(2000)   NULL,
    created_at          timestamptz(3)  NOT NULL DEFAULT now(),
    CONSTRAINT ck_sync_jobs_trigger CHECK (trigger_type IN ('scheduled', 'manual', 'retry')),
    CONSTRAINT ck_sync_jobs_status  CHECK (status IN ('queued', 'running', 'succeeded', 'partially_succeeded', 'failed', 'cancelled')),
    CONSTRAINT ck_sync_jobs_attempt CHECK (attempt >= 1 AND max_attempts >= 1)
);

-- One active job per integration: prevents overlapping / duplicate runs
CREATE UNIQUE INDEX IF NOT EXISTS ux_sync_jobs_one_active ON app.integration_sync_jobs (integration_id)
    WHERE status IN ('queued', 'running');
-- Worker claim
CREATE INDEX IF NOT EXISTS ix_sync_jobs_claim ON app.integration_sync_jobs (run_after) WHERE status = 'queued';
-- History screen, retention purge
CREATE INDEX IF NOT EXISTS ix_sync_jobs_history ON app.integration_sync_jobs (integration_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ix_sync_jobs_finished ON app.integration_sync_jobs (finished_at) WHERE finished_at IS NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_integrations_last_job') THEN
        ALTER TABLE app.integrations ADD CONSTRAINT fk_integrations_last_job
            FOREIGN KEY (last_job_id) REFERENCES app.integration_sync_jobs (id) ON DELETE SET NULL;
    END IF;
END $$;

